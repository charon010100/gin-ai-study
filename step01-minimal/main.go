// Step 1：最小可运行的网站。
//
// 这一步刻意只写 25 行，目的是先把「一个 HTTP 服务是怎么起来的」这件事看清楚。
// 后面每一步都建立在这 25 行之上，所以先花时间把它彻底搞明白。
package main

import (
	"net/http"
	"github.com/gin-gonic/gin"
)

func main() {
	// ① 创建引擎（engine）。
	//
	// gin.Default() = gin.New() + Logger 中间件 + Recovery 中间件。
	// 这两个默认中间件很重要，也正是初学者容易忽略的地方：
	//
	//   - Logger：每处理完一个请求就打印一行访问日志。
	//     你自己手写的 handler 不需要打日志，因为别人（框架）已经帮你打了。
	//   - Recovery：handler 里发生 panic 时，它负责恢复并把 500 返回给客户端。
	//     没有它，一个 panic 就会让整个进程退出——注意，是**整个服务的所有用户**
	//     都断了，而不是只有触发 panic 的那个请求失败。
	//
	// 这两个能力后面都要自己接管（自己写日志格式、自己控制输出），
	// 所以最终会从 gin.Default() 改成 gin.New()，那时会说明原因。
	r := gin.Default()

	// ② 注册路由。
	//
	// 这里面有三个要素，缺一不可：
	//   - "GET"      HTTP 方法。同一个路径注册不同方法，就是不同的路由。
	//   - "/ping"    路径。必须以 / 开头。
	//   - 处理函数   类型必须是 func(*gin.Context)，注意是指针。
	//
	// 关于那个指针：gin.Context 里装着本次请求的全部信息（请求、响应、参数、
	// 中间件之间传递的数据）。它必须是指针，否则函数内部改的东西传不出去。
	// 如果你写成 func(c gin.Context)（少个星号），编译不会报错，
	// 但接口会静默失效——因为你会往一个副本里写响应。
	r.GET("/ping", func(c *gin.Context) {
		// c.JSON 做两件事：设置 Content-Type: application/json; charset=utf-8，
		// 并把 data 用标准库 encoding/json 编码后写入响应体。
		//
		// 状态码用 http.StatusOK 而不是直接写 200：
		// 常量的名字比数字更能表达意图，而且不怕记错（201/204 是另一个意思）。
		c.JSON(http.StatusOK, gin.H{
			"message": "pong",
		})
	})

	// ③ 启动服务，阻塞在这里直到进程被结束。
	//
	// r.Run(":8080") 内部其实就是：
	//   http.ListenAndServe(":8080", r)
	// 所以它等价于启动了一个标准库的 HTTP 服务器，只是 Handler 换成了 gin 引擎。
	//
	// ":8080" 前面的冒号不能省：这表示监听**所有网卡**（0.0.0.0:8080）。
	// 写成 "localhost:8080" 的话，只有本机能访问，
	// 用另一台机器访问就会连接被拒绝——这是新手最常见的「玄学」问题之一。
	//
	// 忽略返回的 error 在这里是可以的（这是最后一行代码，且返回 err 通常意味着
	// 端口被占用，程序即将退出）。但到 Step 3 我们就会正经处理它，
	// 因为「端口被占用」时需要打印一句人能看懂的话，而不是直接死掉。
	_ = r.Run(":8080")
}
